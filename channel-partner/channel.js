function nextPartnerCode() {
  const maxNum = partners.reduce((max, p) => {
    const n = parseInt(p.code.replace(/\D/g, ''), 10);
    return isNaN(n) ? max : Math.max(max, n);
  }, 0);
  return `CP-${String(maxNum + 1).padStart(4, '0')}`;
}

